// The source currently has no notes/descriptions. Keep their translation separate when supplied.
export const noteTranslations: Record<string, Translation> = {};
export function dishName(item: MenuItem, language: Language): string {
  return language === 'ua' ? item.name.trim() : dishTranslations[item.name.trim()]?.[language] ?? item.name.trim();
}
export function dishDescription(item: MenuItem, language: Language): string {
  if (!item.note) return '';
  return language === 'ua' ? item.note : noteTranslations[item.note]?.[language] ?? item.note;
}
export function categoryName(category: { id: string; name: string }, language: Language): string {
  return language === 'ua' ? category.name : categoryTranslations[category.id]?.[language] ?? category.name;
}
export function localizeWeight(weight: string | undefined, language: Language): string {
  if (!weight) return '';
  if (language === 'ua') return weight.replace(/(\d)(г|шт|см)/g, '$1 $2');
  if (weight === 'вихід 350 грам (1,2 або 3 штуки)') {
    return language === 'en' ? 'Serving: 350 g (1,2 or 3 pieces)' : 'Porción: 350 g (1,2 o 3 piezas)';
  }
  return weight.replace(/\s*шт/g, language === 'en' ? ' pcs' : ' uds.').replace(/\s*см/g, ' cm').replace(/\s*г/g, ' g');
}
